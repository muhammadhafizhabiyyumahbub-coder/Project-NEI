def test_execute_timeout_kills_process():
    """Verify _run_rhino_script kills process on timeout."""
    conn = Rhino6Connector()
    timeout = 0.1  # 100ms
    fake_result = {"success": True, "object_ids": []}
    
    # Simulate a hung process that never returns
    def hung_run(script_path, result_path, timeout_s):
        # Sleep longer than timeout
        import time
        time.sleep(10)
        # Never write result
        return None
    
    with patch.object(conn, "_run_rhino_script", side_effect=hung_run):
        result = conn.execute("rhino.create_box_test", {"length": 10.0}, timeout_s=timeout)
    assert result.success is False
    # Timeout causes None result -> error message
    assert "did not produce result" in result.error
def test_box_script_is_python2_compatible():
    """Verify generated box script uses no f-strings or Python 3-only syntax."""
    conn = Rhino6Connector()
    import subprocess, tempfile
    # Extract the script that would be generated by calling _create_box
    fake_result = {
        "success": True,
        "object_ids": ["x"],
        "objects": [],
        "document": {"units": "Millimeters"},
    }
    captured_scripts = []
    def fake_run(script_path, result_path, timeout_s):
        captured_scripts.append(Path(script_path).read_text(encoding="utf-8"))
        return fake_result

    with patch.object(conn, "_run_rhino_script", side_effect=fake_run):
        conn.execute("rhino.create_box_test", {"length": 10.0, "width": 3.0, "height": 1.0}, timeout_s=5)

    assert captured_scripts, "no script captured"
    script = captured_scripts[0]
    assert "f'" not in script, "f-string detected — not Python 2.7 compatible"
    assert "print(" not in script or "from __future__" in script
    assert "10.0" in script
    assert "3.0" in script
    assert "1.0" in script



def test_detect_not_found():
    conn = Rhino6Connector(rhino_exe="C:\\nonexistent\\Rhino.exe")
    det = conn.detect()
    assert det.detected is False


def test_detect_found(tmp_path):
    exe = tmp_path / "Rhino.exe"
    exe.write_text("")
    conn = Rhino6Connector(rhino_exe=str(exe))
    det = conn.detect()
    assert det.detected is True
    assert det.exe_path == str(exe)



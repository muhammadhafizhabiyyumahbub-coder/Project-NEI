def test_create_box_script_generation():
    conn = Rhino6Connector()
    # Mock _run_rhino_script to return a successful result dict
    fake_result = {
        "success": True,
        "object_ids": ["abc-123"],
        "objects": [{
            "id": "abc-123",
            "type": "Brep",
            "bounding_box": {"length": 10.0, "width": 3.0, "height": 1.0},
        }],
        "document": {"units": "Millimeters"},
    }
    with patch.object(conn, "_run_rhino_script", return_value=fake_result):
        result = conn.execute(
            "rhino.create_box_test",
            {"length": 10.0, "width": 3.0, "height": 1.0},
            timeout_s=5,
        )
    assert result.success is True
    assert result.object_ids == ["abc-123"]
    assert result.data["objects"][0]["bounding_box"]["length"] == 10.0


